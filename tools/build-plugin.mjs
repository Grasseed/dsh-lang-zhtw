// Convert extracted Simplified dictionaries to Traditional (TW usage) with
// OpenCC and emit the complete @local/dsh-lang-zhtw plugin package.
import fs from 'node:fs';
import path from 'node:path';
import OpenCC from 'opencc-js';

const OUT_DIR = path.resolve(import.meta.dirname, '..');
const dicts = JSON.parse(fs.readFileSync('/tmp/zh-dicts-merged.json', 'utf8'));

const converter = OpenCC.Converter({ from: 'cn', to: 'twp' }); // s2twp: chars + TW phrasing

// namespaces that don't appear in the web GUI (Electron main process) or are test data
const BLOCK_NS = new Set(['crash-']);
const blockKey = (ns) => ns.startsWith('data-') || ns.endsWith('-');

const out = {};
// Post-conversion TW usage fixes for terms OpenCC's phrase dict misses in UI context.
const POLISH = [
  ['計劃', '計畫'], // UI nouns (plan feature) use 計畫 in Taiwan
  ['許可權', '權限'], // TW UI convention is 權限 (OpenCC's 許可權 is mainland-flavored)
  ['擴充套件', '擴展'], // 扩展 as verb/noun stays 擴展; OpenCC over-maps to 擴充套件
];
let total = 0;
let phSrc = 0, phOut = 0;
// Dictionary values may nest (arrays of guide paragraphs, grouped entries);
// convert every string leaf while preserving structure.
function deepConvert(v) {
  if (typeof v === 'string') {
    let t = converter(v);
    for (const [a, b] of POLISH) t = t.split(a).join(b);
    phSrc += (v.match(/\{[A-Za-z0-9_.]+\}/g) ?? []).length;
    phOut += (t.match(/\{[A-Za-z0-9_.]+\}/g) ?? []).length;
    return t;
  }
  if (Array.isArray(v)) return v.map(deepConvert);
  if (v && typeof v === 'object') {
    const o = {};
    for (const [k, inner] of Object.entries(v)) o[k] = deepConvert(inner);
    return o;
  }
  return v;
}
for (const [ns, dict] of Object.entries(dicts)) {
  if (BLOCK_NS.has(ns) || blockKey(ns)) continue;
  const conv = {};
  for (const [k, v] of Object.entries(dict)) {
    if (typeof v === 'string' || (v && typeof v === 'object')) conv[k] = deepConvert(v);
  }
  if (Object.keys(conv).length) { out[ns] = conv; total += Object.keys(conv).length; }
}
fs.writeFileSync('/tmp/zh-tw-dicts.json', JSON.stringify(out, null, 1));
console.log('converted namespaces:', Object.keys(out).length, '| keys:', total);

/* ---------- sanity spot checks (placeholders preserved?) ---------- */
console.log('placeholder count source/output:', phSrc, phOut, phSrc === phOut ? 'OK' : 'MISMATCH!');
for (const probe of ['服务器', '默认', '搜索', '设置', '软件', '删除', '会话', '计划']) {
  const hit = Object.values(dicts).flatMap((d) => Object.values(d)).find((v) => typeof v === 'string' && v.includes(probe));
  if (hit) console.log(`probe ${probe}: ${converter(hit)}`);
}

/* ---------- emit plugin package ---------- */
const pkg = {
  name: 'dsh-lang-zhtw',
  version: '1.0.0',
  type: 'module',
  license: 'MIT',
  description: '繁體中文（台灣）語言包：以 OpenCC 轉換 DSH 內建簡體介面字典，未覆蓋字串自動退回簡體。Traditional Chinese (Taiwan) language pack for DeepSeek Harness.',
  keywords: ['dsh-plugin', 'deepseek-harness', 'language-pack', 'zh-TW', 'traditional-chinese'],
  repository: { type: 'git', url: 'git+https://github.com/Grasseed/dsh-lang-zhtw.git' },
  author: 'Grasseed',
  devDependencies: { 'opencc-js': '^1.3.1' },
  exports: {
    '.': './index.js',
    './client': './client.js',
    './locale/*.json': './locale/*.json',
    './icon': './icon.svg',
  },
  files: ['index.js', 'client.js', 'cordis.patch.yml', 'locale/*.json', 'icon.svg'],
  dsh: {
    bundle: { patch: './cordis.patch.yml' },
    client: { platform: 'web', immediately: true, inject: ['@deepseek-ai/dsh-client-locale'] },
  },
};
fs.mkdirSync(path.join(OUT_DIR, 'locale'), { recursive: true });
fs.writeFileSync(path.join(OUT_DIR, 'package.json'), JSON.stringify(pkg, null, 2) + '\n');

fs.writeFileSync(path.join(OUT_DIR, 'index.js'), `// Host half: a locale language pack needs no Host services.
export function apply() {}
`);

fs.writeFileSync(path.join(OUT_DIR, 'cordis.patch.yml'), `- insert:
    - id: lang-zhtw
      name: 'dsh-lang-zhtw'
`);

// The browser plugin loader executes client.js as a classic script, so the
// dictionaries are inlined (no ESM imports, no extra module ids).
const nsBlocks = Object.entries(out)
  .sort((a, b) => Object.keys(b[1]).length - Object.keys(a[1]).length)
  .map(([ns, d]) => `\t\t\t${JSON.stringify(ns)}: ${JSON.stringify(d)},`)
  .join('\n');
fs.writeFileSync(path.join(OUT_DIR, 'client.js'), `// Registers 繁體中文（台灣）as a client language pack.
// Generated by tools/build-plugin.mjs from the shipped dictionaries of DeepSeek
// Harness via OpenCC (cn -> twp) plus a small TW-usage polish table.
// Lookup chain: zh-TW -> zh -> en, so any key not covered here falls back to
// the shipped Simplified dictionary; untranslated internals keep working.
window.__ModuleLoader__.load({
\tid: 'dsh-lang-zhtw',
\tfactory(require) {
\t\tconst DICTIONARIES = {
${nsBlocks}
\t\t};
\t\treturn {
\t\t\tinject: ['locale'],
\t\t\tapply(ctx) {
\t\t\t\tctx.effect(
\t\t\t\t\t() => ctx.locale.addLanguage({ id: 'zh-TW', label: '繁體中文（台灣）', fallback: 'zh' }),
\t\t\t\t\t'lang-zhtw: language',
\t\t\t\t);
\t\t\t\tfor (const [ns, dict] of Object.entries(DICTIONARIES)) {
\t\t\t\t\tctx.effect(
\t\t\t\t\t\t() => ctx.locale.register(ns, 'zh-TW', dict),
\t\t\t\t\t\t'lang-zhtw: dictionary ' + ns,
\t\t\t\t\t);
\t\t\t\t}
\t\t\t},
\t\t};
\t},
});
`);
fs.rmSync(path.join(OUT_DIR, 'dictionaries.js'), { force: true });

const metaEn = { meta: { title: 'Traditional Chinese (TW) language pack', description: 'Adds 繁體中文（台灣）to the language selector by converting the shipped Simplified UI dictionary of DSH with OpenCC; uncovered strings fall back to the built-in Chinese.' } };
const metaZh = { meta: { title: '繁体中文（台湾）语言包', description: '用 OpenCC 把 DSH 内建简体中文界面字典转换为台湾繁体并注册为语言包；未覆盖的字符串自动退回内建中文。' } };
const metaZhtw = { meta: { title: '繁體中文（台灣）語言包', description: '用 OpenCC 將 DSH 內建簡體中文介面字典轉換為台灣繁體並註冊為語言包；未覆蓋的字串自動退回內建中文。' } };
fs.writeFileSync(path.join(OUT_DIR, 'locale', 'en.json'), JSON.stringify(metaEn, null, 2) + '\n');
fs.writeFileSync(path.join(OUT_DIR, 'locale', 'zh.json'), JSON.stringify(metaZh, null, 2) + '\n');
fs.writeFileSync(path.join(OUT_DIR, 'locale', 'zh-TW.json'), JSON.stringify(metaZhtw, null, 2) + '\n');

fs.writeFileSync(path.join(OUT_DIR, 'icon.svg'), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="64" height="64">
  <rect x="4" y="4" width="56" height="56" rx="12" fill="#1f6feb"/>
  <text x="32" y="42" font-family="Noto Sans TC, PingFang TC, sans-serif" font-size="26" font-weight="700" text-anchor="middle" fill="#ffffff">繁</text>
</svg>
`);
console.log('plugin written to', OUT_DIR);
